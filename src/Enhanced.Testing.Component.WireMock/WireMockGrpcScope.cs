using System.Collections.Concurrent;
using Grpc.Core;

namespace Enhanced.Testing.Component.WireMock;

/// <summary>
///     A scope of a <see cref="WireMockGrpcHarness" />, for one test that shares the harness with others: the
///     stubs made through the scope are removed when it is disposed, and it sees only the requests received since
///     it began.
/// </summary>
/// <remarks>
///     Stubs made through the harness itself are not touched: they are the defaults of the fixture. Scopes of
///     tests that run at the same time do not remove each other's stubs, but each sees the requests the other
///     tests cause; tell them apart by an id of the test's own.
/// </remarks>
public class WireMockGrpcScope : IDisposable
{
    private readonly WireMockGrpcHarness _harness;
    private readonly ConcurrentDictionary<Type, object> _services = new();
    private readonly List<WireMockGrpcStub> _stubs = [];
    private bool _disposed;

    internal WireMockGrpcScope(WireMockGrpcHarness harness)
    {
        _harness = harness;
        Began = DateTime.UtcNow;
    }

    internal DateTime Began { get; }

    /// <summary>
    ///     Returns the stubs and the requests of a gRPC service within this scope.
    /// </summary>
    /// <typeparam name="TClient">
    ///     The client of the service that <c>Grpc.Tools</c> generated, for example <c>Greeter.GreeterClient</c>.
    /// </typeparam>
    /// <returns>
    ///     The service; the same instance for the same client type.
    /// </returns>
    /// <exception cref="InvalidOperationException">
    ///     Thrown if <typeparamref name="TClient" /> is not a client generated by <c>Grpc.Tools</c>.
    /// </exception>
    public WireMockGrpcService<TClient> Service<TClient>()
        where TClient : ClientBase<TClient>
    {
        return (WireMockGrpcService<TClient>)_services.GetOrAdd(typeof(TClient),
            static (_, scope) => new WireMockGrpcService<TClient>(scope._harness, scope), this);
    }

    /// <summary>
    ///     Removes the stubs made through the scope.
    /// </summary>
    public void Dispose()
    {
        WireMockGrpcStub[] stubs;

        lock (_stubs)
        {
            _disposed = true;
            stubs = _stubs.ToArray();
            _stubs.Clear();
        }

        foreach (var stub in stubs)
        {
            stub.Dispose();
        }
    }

    internal void Add(WireMockGrpcStub stub)
    {
        lock (_stubs)
        {
            ObjectDisposedException.ThrowIf(_disposed, this);
            _stubs.Add(stub);
        }
    }
}
