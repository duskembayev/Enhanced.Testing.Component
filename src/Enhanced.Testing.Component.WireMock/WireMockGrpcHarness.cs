using System.Collections.Concurrent;
using Grpc.Core;

namespace Enhanced.Testing.Component.WireMock;

/// <summary>
///     A WireMock harness that fakes a gRPC backend the application calls. The server listens over HTTP/2, and
///     stubs are described through the generated clients of the services: see <see cref="Service{TClient}" />.
/// </summary>
/// <remarks>
///     Use it for a backend that hosts several gRPC services on one address; for a backend with one service,
///     <see cref="WireMockGrpcHarness{TClient}" /> is shorter. The extensions of
///     <see cref="WireMockGrpcExtensions" /> and <see cref="WireMockHarness.Server" /> stay available for what the
///     stubs of this harness do not cover.
/// </remarks>
public class WireMockGrpcHarness : WireMockHarness
{
    private readonly ConcurrentDictionary<Type, object> _services = new();
    private int _stubs;

    /// <summary>
    ///     Creates a harness whose server listens over HTTP/2.
    /// </summary>
    public WireMockGrpcHarness()
    {
        UseHttp2 = true;
    }

    /// <summary>
    ///     Returns the stubs of a gRPC service of this backend.
    /// </summary>
    /// <typeparam name="TClient">
    ///     The client of the service that <c>Grpc.Tools</c> generated, for example <c>Greeter.GreeterClient</c>.
    /// </typeparam>
    /// <returns>
    ///     The service; the same instance for the same client type.
    /// </returns>
    /// <exception cref="InvalidOperationException">
    ///     Thrown if <typeparamref name="TClient" /> is not a client generated by <c>Grpc.Tools</c>.
    /// </exception>
    public WireMockGrpcService<TClient> Service<TClient>()
        where TClient : ClientBase<TClient>
    {
        return (WireMockGrpcService<TClient>)_services.GetOrAdd(typeof(TClient),
            static (_, harness) => new WireMockGrpcService<TClient>(harness), this);
    }

    internal int NextStub() => Interlocked.Increment(ref _stubs);
}
